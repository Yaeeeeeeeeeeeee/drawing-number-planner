import { useEffect, useMemo, useRef, useState } from 'react';
import { CopyButton } from '../../components/CopyButton';
import type { OutboundContactView, OutboundEmailTemplateView, OutboundMaterialTypeView, OutboundSignatureView, PlannerApi } from '../../data/client';
import type { OutboundMailContext } from './PackageBuilder';
import { RecipientPicker } from './RecipientPicker';
import { DraftChangeEditor } from './DraftChangeEditor';
import { describeChanges, draftChanges, fileBaseName, unresolvedVariables, type DraftChange } from './mail-draft';
import './mail-draft.css';

interface EmailComposerProps { api: PlannerApi; mailContext: OutboundMailContext | null; filterRecipients?: boolean; refreshRevision?: number }
const UNSCOPED = '__unscoped__';
const manufacturerKey = (value?: string | null) => value?.trim() || UNSCOPED;
const scenarioKey = (value?: string | null) => value?.trim() || UNSCOPED;

export function EmailComposer({ api, mailContext: incomingContext, filterRecipients = false, refreshRevision = 0 }: EmailComposerProps) {
  const [mailContext, setMailContext] = useState(incomingContext);
  const [pendingContext, setPendingContext] = useState<OutboundMailContext | null>(null);
  const lastIncoming = useRef(incomingContext);
  const generationRevision = useRef(0);
  const autoGeneratedContext = useRef<OutboundMailContext | null>(null);
  const renderedChanges = useRef('');
  const [contacts, setContacts] = useState<OutboundContactView[]>([]);
  const [templates, setTemplates] = useState<OutboundEmailTemplateView[]>([]);
  const [signatures, setSignatures] = useState<OutboundSignatureView[]>([]);
  const [to, setTo] = useState<number[]>([]);
  const [cc, setCc] = useState<number[]>([]);
  const [toOverride, setToOverride] = useState<string | null>(null);
  const [ccOverride, setCcOverride] = useState<string | null>(null);
  const [manufacturer, setManufacturer] = useState(incomingContext?.manufacturer?.trim() ?? '');
  const [scenario, setScenario] = useState(incomingContext?.scenario?.trim() ?? '');
  const [templateId, setTemplateId] = useState('');
  const [signatureId, setSignatureId] = useState('');
  const loadedChoices = useRef(false);
  const contactManufacturer = useRef('');
  const recipientSelectionEdited = useRef(false);
  const [blocks, setBlocks] = useState<number[]>([]);
  const [subject, setSubject] = useState(mailContext?.packageName ?? '');
  const [body, setBody] = useState('');
  const [manuallyEdited, setManuallyEdited] = useState(false);
  const [changeEdited, setChangeEdited] = useState(false);
  const [materialType, setMaterialType] = useState<OutboundMaterialTypeView>(mailContext?.materialType ?? 'update');
  const [changes, setChanges] = useState<DraftChange[]>(() => draftChanges(incomingContext));
  const [message, setMessage] = useState('');
  const [copyFeedback, setCopyFeedback] = useState<Record<string, string>>({});
  const uncertainChanges = materialType === 'update' && !!mailContext?.items.some(item => !item.change || item.changeVerified === false);
  const changeText = materialType === 'update' ? describeChanges(changes, true) : '';
  const descriptionText = changeText;

  const adoptContext = (context: OutboundMailContext) => {
    generationRevision.current += 1;
    setMailContext(context); setSubject(context.packageName); setBody('');
    setMaterialType(context.materialType); setChanges(draftChanges(context));
    setManufacturer(context.manufacturer?.trim() ?? '');
    setScenario(context.scenario?.trim() ?? '');
    setManuallyEdited(false); setChangeEdited(false); setPendingContext(null);
    autoGeneratedContext.current = null;
  };
  useEffect(() => () => { generationRevision.current += 1; }, [api]);
  useEffect(() => {
    if (incomingContext === lastIncoming.current) return;
    lastIncoming.current = incomingContext;
    generationRevision.current += 1;
    if (!incomingContext) return;
    if (manuallyEdited || changeEdited) setPendingContext(incomingContext);
    else adoptContext(incomingContext);
  }, [incomingContext]);

  useEffect(() => {
    let current = true; generationRevision.current += 1;
    void Promise.all([api.listOutboundContacts('active'), api.listOutboundTemplates('active'), api.listOutboundSignatures('active')])
      .then(([nextContacts, nextTemplates, nextSignatures]) => {
        if (!current) return;
        setContacts(nextContacts); setTemplates(nextTemplates); setSignatures(nextSignatures);
        setTo(value => value.filter(id => nextContacts.some(item => item.id === id)));
        setCc(value => value.filter(id => nextContacts.some(item => item.id === id)));
        setBlocks(value => value.filter(id => nextTemplates.some(item => item.blocks.some(block => block.id === id && block.status === 'active'))));
        const preferred = nextSignatures.find(item => item.isDefault) ?? nextSignatures[0];
        const keepNone = loadedChoices.current;
        setSignatureId(previous => (keepNone && !previous) || nextSignatures.some(item => String(item.id) === previous) ? previous : preferred ? String(preferred.id) : '');
        loadedChoices.current = true;
      }).catch(error => { if (current) setMessage(error instanceof Error ? error.message : '邮件资料加载失败'); });
    return () => { current = false; };
  }, [api, refreshRevision]);

  const manufacturers = useMemo(() => [...new Set([...templates.map(item => manufacturerKey(item.manufacturer)), ...contacts.map(item => manufacturerKey(item.company)), ...(mailContext?.manufacturer ? [mailContext.manufacturer] : [])])], [templates, contacts, mailContext]);
  const manufacturerTemplates = templates.filter(item => manufacturerKey(item.manufacturer) === manufacturer && item.materialType === materialType);
  const scenarios = [...new Set(manufacturerTemplates.map(item => scenarioKey(item.scenario)))];
  const matchingTemplates = manufacturerTemplates.filter(item => scenarioKey(item.scenario) === scenario);
  // There is no arbitrary first manufacturer or first scenario. A unique scenario is safe after manufacturer selection.
  useEffect(() => {
    if (!manufacturer) { setScenario(''); setTemplateId(''); return; }
    if (!scenario && scenarios.length === 1) setScenario(scenarios[0]);
  }, [manufacturer, scenario, materialType, templates]);
  useEffect(() => {
    setTemplateId(previous => matchingTemplates.some(item => String(item.id) === previous) ? previous : matchingTemplates.length === 1 ? String(matchingTemplates[0].id) : '');
    setBlocks([]);
  }, [manufacturer, scenario, materialType, templates]);
  useEffect(() => {
    const manufacturerChanged = contactManufacturer.current !== manufacturer;
    contactManufacturer.current = manufacturer;
    if (manufacturerChanged) {
      recipientSelectionEdited.current = false;
      setToOverride(null); setCcOverride(null);
    }
    if (manufacturerChanged || !recipientSelectionEdited.current) {
      const matching = manufacturer && manufacturer !== UNSCOPED ? contacts.filter(item => item.company.trim() === manufacturer) : [];
      setTo(matching.filter(item => item.defaultRecipientType === 'to').map(item => item.id));
      setCc(matching.filter(item => item.defaultRecipientType === 'cc').map(item => item.id));
    }
  }, [manufacturer, contacts]);

  const template = matchingTemplates.find(item => item.id === Number(templateId));
  const signature = signatures.find(item => item.id === Number(signatureId));
  const recipientContacts = manufacturer && manufacturer !== UNSCOPED ? contacts.filter(item => item.company.trim() === manufacturer) : contacts;
  const toText = toOverride ?? contacts.filter(item => to.includes(item.id)).map(item => item.email).join('; ');
  const ccText = ccOverride ?? contacts.filter(item => cc.includes(item.id)).map(item => item.email).join('; ');
  const optionalText = template?.blocks.filter(item => blocks.includes(item.id)).map(item => item.bodyTemplate).join('\n') ?? '';
  const fileList = useMemo(() => {
    const files = mailContext?.items.map(item => `  ${fileBaseName(item.fileName)}`).join('\n') ?? '';
    const packages = mailContext?.packageFiles ?? [];
    return packages.length > 1 ? `${files}\n\n分包附件：\n${packages.map(name => `  ${fileBaseName(name)}`).join('\n')}` : files;
  }, [mailContext]);

  const generate = async (automatic = false) => {
    if (!template || uncertainChanges) return;
    if (manuallyEdited && (automatic || !window.confirm('重新生成将替换您已修改的主题和正文，是否继续？'))) return;
    const revision = ++generationRevision.current; setMessage('');
    renderedChanges.current = changeText;
    const primary = contacts.find(item => to.includes(item.id));
    try {
      const rendered = await api.renderOutboundTemplate(template.id, {
        package_name: mailContext?.packageName ?? subject,
        brand: mailContext?.product.brandName ?? '', brand_name: mailContext?.product.brandName ?? '',
        model: mailContext?.product.model ?? '', category: mailContext?.product.productCategory ?? '', product_category: mailContext?.product.productCategory ?? '',
        date: (mailContext?.createdAt ? new Date(mailContext.createdAt) : new Date()).toLocaleDateString('sv-SE'),
        batch: mailContext?.batchName ?? '', count: String(mailContext?.packageFiles?.length ?? 0),
        company_name: manufacturer === UNSCOPED ? primary?.company ?? '' : manufacturer,
        contact_salutation: primary?.contactName ?? '',
        change_description: descriptionText, change_files: changeText,
        package_files: (mailContext?.packageFiles?.length ?? 0) > 1 ? `分包附件：\n${mailContext!.packageFiles!.map(name => `  ${fileBaseName(name)}`).join('\n')}` : (mailContext?.packageFiles ?? []).map(fileBaseName).join('\n'),
        file_list: fileList, optional_blocks: optionalText, signature: signature?.content ?? '',
      });
      if (revision !== generationRevision.current) return;
      if (unresolvedVariables(`${rendered.subject}\n${rendered.body}`)) throw new Error('邮件中存在未替换变量，请补充必要资料后重新生成。');
      let nextBody = rendered.body;
      if (materialType === 'update' && changeText && !/\{\{\s*(?:change_files|change_description)\s*\}\}/.test([template.bodyTemplate, optionalText].join('\n'))) {
        const signatureText = signature?.content.trim() ?? '';
        const trimmed = nextBody.trimEnd();
        const insertion = `本次修改的内容为：\n\n${changeText}`;
        nextBody = signatureText && trimmed.endsWith(signatureText)
          ? `${trimmed.slice(0, -signatureText.length).trimEnd()}\n\n${insertion}\n\n${signatureText}`
          : `${trimmed}\n\n${insertion}`;
      }
      setSubject(rendered.subject); setBody(nextBody); setManuallyEdited(false);
    } catch (error) { if (revision === generationRevision.current) setMessage(error instanceof Error ? error.message : '邮件内容生成失败'); }
  };

  useEffect(() => {
    if (!mailContext || !template || uncertainChanges || autoGeneratedContext.current === mailContext || manuallyEdited) return;
    autoGeneratedContext.current = mailContext; void generate(true);
  }, [mailContext, template, signature, uncertainChanges]);
  useEffect(() => {
    if (mailContext && template && autoGeneratedContext.current === mailContext && !manuallyEdited && renderedChanges.current !== changeText) void generate(true);
  }, [changeText]);
  const updateChanges = (next: DraftChange[]) => { setChanges(next); setChangeEdited(true); };
  const toggle = (list: number[], id: number, setter: (value: number[]) => void, clear: (value: string | null) => void) => { recipientSelectionEdited.current = true; setter(list.includes(id) ? list.filter(value => value !== id) : [...list, id]); clear(null); };
  const copyField = async (key: string, text: string) => {
    if (unresolvedVariables(text)) { setMessage('邮件中存在未替换变量，请补充后再复制。'); return; }
    try { await navigator.clipboard.writeText(text); setCopyFeedback(previous => ({ ...previous, [key]: '已复制' })); if (!filterRecipients || key === 'all') setMessage('已复制'); }
    catch { setMessage('复制失败，请手动选择文本'); }
  };
  const copyButton = (key: string, label: string, text: string) => <CopyButton label={label} className="text-button email-copy-button" type="button" title={label} onClick={() => void copyField(key, text)}>{filterRecipients && copyFeedback[key] && <span className="ob-copy-feedback" role="status">{copyFeedback[key]}</span>}</CopyButton>;
  return <section className="outbound-panel email-composer" onChangeCapture={() => { generationRevision.current += 1; }}>
    {mailContext?.appearanceLabel && <p className="muted-text">外观版本：{mailContext.appearanceLabel}{mailContext.bomVersionIds?.length ? ` · BOM 记录 ${mailContext.bomVersionIds.join('、')}` : ''}</p>}
    {pendingContext && <div className="info-banner">新压缩包已生成：{pendingContext.packageName}。当前邮件仍保留原资料和已编辑内容。<button type="button" className="text-button" onClick={() => { if (window.confirm('使用新压缩包将替换当前邮件主题和修改明细，并清空正文。是否继续？')) adoptContext(pendingContext); }}>使用新压缩包资料</button></div>}
    <div className="email-workspace"><section className="email-generation-settings" aria-label="邮件生成设置"><h3>生成设置</h3>
      <div className="email-settings-row">
        <label><span>适用厂家</span><select aria-label="适用厂家" value={manufacturer} onChange={event => { setManufacturer(event.target.value); setScenario(''); }}><option value="">请选择厂家</option>{manufacturers.map(value => <option key={value} value={value}>{value === UNSCOPED ? '未指定厂家（现有通用模板）' : value}</option>)}</select></label>
        <label><span>资料类型</span><select aria-label="邮件资料类型" value={materialType} onChange={event => { setMaterialType(event.target.value as OutboundMaterialTypeView); setScenario(''); }}><option value="initial">首批资料</option><option value="update">更新资料</option></select></label>
        <label><span>邮件场景</span><select aria-label="邮件场景" value={scenario} onChange={event => setScenario(event.target.value)}><option value="">请选择场景</option>{scenario && !scenarios.includes(scenario) && <option value={scenario}>{scenario}（暂无模板）</option>}{scenarios.map(value => <option key={value} value={value}>{value === UNSCOPED ? '现有通用场景' : value}</option>)}</select></label>
        <label><span>邮件模板</span><select aria-label="邮件模板" value={templateId} onChange={event => { setTemplateId(event.target.value); setBlocks([]); }}><option value="">请选择</option>{matchingTemplates.map(item => <option value={item.id} key={item.id}>{item.name}</option>)}</select></label>
        <label><span>签名</span><select aria-label="邮件签名" value={signatureId} onChange={event => setSignatureId(event.target.value)}><option value="">不使用</option>{signatures.map(item => <option value={item.id} key={item.id}>{item.name}</option>)}</select></label>
      </div>
      {!manufacturer && <p className="info-banner">本次外发未提供厂家，请明确选择适用厂家。</p>}
      {manufacturer && !matchingTemplates.length && <p className="info-banner">没有匹配厂家、资料类型和场景的模板，请选择场景或先在邮件配置中维护模板。</p>}
      {uncertainChanges && <p className="error-banner" role="alert">变更状态尚未确认，请返回外发清单核对并确认真实变化，再重新生成 ZIP。邮件不会自动宣称这些文件已经变更。</p>}
      {materialType === 'update' && <DraftChangeEditor key={mailContext?.packageId ?? mailContext?.packageName ?? 'none'} changes={changes} onChange={updateChanges} />}
      {manuallyEdited && changeEdited && <p className="info-banner">已保留直接编辑的正文。变更说明已修改，请点击生成邮件内容并确认替换。</p>}
      {mailContext?.packageFiles?.length ? <p className="muted-text mail-zip-info">本次 ZIP：{mailContext.packageFiles.map(fileBaseName).join('、')}</p> : null}
      {(['to', 'cc'] as const).map(kind => {
        const label = kind === 'to' ? '收件人' : '抄送'; const selected = kind === 'to' ? to : cc; const setter = kind === 'to' ? setTo : setCc; const clear = kind === 'to' ? setToOverride : setCcOverride; const text = kind === 'to' ? toText : ccText;
        return <section className="ob-recipient-group" key={kind}><h4>{label}</h4>{filterRecipients ? <RecipientPicker label={label} contacts={recipientContacts} selected={selected} onChange={ids => { recipientSelectionEdited.current = true; setter(ids); clear(null); }} /> : <fieldset><legend>{label}</legend>{recipientContacts.map(item => <label key={item.id}><input type="checkbox" aria-label={`${label} ${item.contactName}`} checked={selected.includes(item.id)} onChange={() => toggle(selected, item.id, setter, clear)} />{item.company} · {item.contactName} · {item.email}</label>)}</fieldset>}<label><span>{label}地址</span><input aria-label={`${label}文本`} value={text} onChange={event => clear(event.target.value)} /></label>{copyButton(`${kind}Text`, `复制${label}`, text)}</section>;
      })}
      {template?.blocks.length ? <fieldset><legend>可选附加段落</legend>{template.blocks.filter(item => item.status === 'active').map(item => <label key={item.id}><input type="checkbox" aria-label={`附加段落 ${item.name}`} checked={blocks.includes(item.id)} onChange={() => setBlocks(value => value.includes(item.id) ? value.filter(id => id !== item.id) : [...value, item.id])} />{item.name}</label>)}</fieldset> : null}
      <button className="secondary-button" type="button" disabled={!template || uncertainChanges} onClick={() => void generate()}>生成邮件内容</button>
    </section><section className="email-draft-content" aria-label="邮件草稿内容"><h3>草稿内容</h3>
      <label><span>主题</span><input aria-label="主题" value={subject} onChange={event => { setSubject(event.target.value); setManuallyEdited(true); }} /></label>{copyButton('subject', '复制主题', subject)}
      <label><span>正文</span><textarea aria-label="正文" rows={14} value={body} onChange={event => { setBody(event.target.value); setManuallyEdited(true); }} /></label>{copyButton('body', '复制正文', body)}
      <CopyButton label="复制邮件内容" className="primary-button" type="button" onClick={() => void copyField('all', `收件人：${toText}\n抄送：${ccText}\n主题：${subject}\n正文：\n${body}`)} />
    </section></div>
    {message && <p role="status" className={message === '已复制' ? 'muted-text' : 'error-banner'}>{message}</p>}
  </section>;
}
