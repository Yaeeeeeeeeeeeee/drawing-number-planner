import { fireEvent, render, screen } from '@testing-library/react';
import { afterEach, describe, expect, it, vi } from 'vitest';
import { App } from '../../src/renderer/App';
import { createFilesMockApi } from '../../src/renderer/pages/files-mock';

afterEach(() => { window.history.replaceState({}, '', '/'); delete window.plannerDesktop; vi.unstubAllGlobals(); });
describe('PDF renderer-only preview isolation', () => {
  it('keeps explicit batch absence separate from file presence and drawing matching', async () => {
    window.history.replaceState({}, '', '/?mock=files&files-scenario=anomalies');
    const real = vi.fn(() => { throw new Error('REAL API MUST NOT RUN'); });
    render(<App api={new Proxy({}, { get: () => real }) as never} />);
    await screen.findAllByText('批次缺失');
    const row = document.querySelector('.files-batch.missing')!.closest('tr')!;
    expect(row.querySelector('.presence-label.present')).toHaveTextContent('存在');
    expect(row.querySelector('.file-match.conflict')).toHaveTextContent('多图号冲突');
    expect(real).not.toHaveBeenCalled();
  });
  it('shows and copies the complete indexed path without file or network access', async () => {
    window.history.replaceState({}, '', '/?mock=files&files-scenario=long');
    const writeText = vi.fn().mockResolvedValue(undefined);
    const originalNavigator = navigator;
    vi.stubGlobal('navigator', new Proxy(originalNavigator, { get: (target, key) => key === 'clipboard' ? { writeText } : Reflect.get(target, key) }));
    const real = vi.fn(() => { throw new Error('REAL API MUST NOT RUN'); });
    const network = vi.fn(); vi.stubGlobal('fetch', network);
    render(<App api={new Proxy({}, { get: () => real }) as never} />);
    const summaries = await screen.findAllByLabelText(/查看 .* 的完整相对路径/);
    fireEvent.click(summaries[0]);
    const full = document.querySelector('.files-path-full')!;
    expect(full.textContent).toContain('/');
    fireEvent.click(screen.getAllByRole('button', { name: /复制 .* 的完整相对路径/ })[0]);
    await screen.findByText('已复制');
    expect(writeText).toHaveBeenCalledWith(full.textContent);
    expect(full.closest('td')).toHaveAttribute('colspan', '10');
    expect(document.querySelector('.files-full-name')).toBeNull();
    fireEvent.click(screen.getByRole('button', { name: '收起路径' }));
    expect(document.querySelector('.files-path-full')).toBeNull();
    expect(summaries[0]).toHaveFocus();
    expect(real).not.toHaveBeenCalled(); expect(network).not.toHaveBeenCalled();
  });
  it('opens files directly without recovery, business API, or desktop calls', async () => {
    window.history.replaceState({}, '', '/?mock=files');
    const real = vi.fn(() => { throw new Error('REAL API MUST NOT RUN'); });
    const desktop = vi.fn(); window.plannerDesktop = { showFileInFolder: desktop };
    const network = vi.fn(); vi.stubGlobal('fetch', network);
    render(<App api={new Proxy({}, { get: () => real }) as never} />);
    await screen.findByText('说明书-001-源文件');
    expect(document.querySelector('.files-page .file-relative')).toBeNull();
    expect(document.querySelector('.file-match.matched .files-match-badge')).toHaveTextContent('已匹配');
    expect(document.querySelector('.files-batch.current .files-status')).toHaveTextContent('当前批次');
    expect(screen.getAllByRole('checkbox')[0]).toBeDisabled();
    expect(screen.getByText(/仅缺失记录可选/)).toBeVisible();
    expect(screen.queryByRole('columnheader', { name: /大小/ })).not.toBeInTheDocument();
    expect(screen.queryByRole('columnheader', { name: '修改时间' })).not.toBeInTheDocument();
    expect(screen.getAllByRole('row')).toHaveLength(51);
    fireEvent.click(screen.getAllByRole('button', { name: /打开 .* 的位置/ })[0]);
    await screen.findByText(/Mock：文件定位已隔离/);
    fireEvent.click(screen.getByRole('button', { name: '扫描资料库' }));
    await screen.findByText('资料库扫描完成');
    fireEvent.click(screen.getByText('索引维护'));
    fireEvent.click(screen.getByRole('button', { name: '清空资料库索引' }));
    await screen.findByRole('dialog', { name: '确认清空资料库索引' });
    fireEvent.click(screen.getByRole('button', { name: '继续' }));
    fireEvent.change(screen.getByLabelText('确认短语'), { target: { value: '清空资料库索引' } });
    fireEvent.click(screen.getByRole('button', { name: '确认清空资料库索引' }));
    await screen.findByText(/已清空 .*条 PDF 索引/);
    expect(real).not.toHaveBeenCalled(); expect(network).not.toHaveBeenCalled(); expect(desktop).not.toHaveBeenCalled();
  });
  it('fails closed for unknown methods and isolates cancellation and cleanup', async () => {
    const api = createFilesMockApi('normal');
    const before = await api.searchPdfFiles({ presence: 'all', pageSize: 200 });
    expect(before.total).toBe(150);
    const missing = before.items.find(row => !row.isPresent)!;
    expect(await api.cleanupPdfFiles([missing.id])).toEqual({ cleaned: 1 });
    await expect(api.cleanupPdfFiles([1])).rejects.toThrow();
    await expect(api.clearFileIndex('wrong')).rejects.toThrow();
    await expect(api.getBomVersion(1)).rejects.toThrow(/隔离/);
    const scanning = api.scanPdfFiles();
    const tasks = await api.listLocalTasks(); expect(tasks[0].status).toBe('running');
    await api.cancelLocalTask(tasks[0].id);
    await expect(scanning).rejects.toThrow(/取消/);
    expect((await api.searchPdfFiles({ presence: 'all' })).total).toBe(149);
  });
  it('isolates missing cleanup and cancellation through actual UI controls', async () => {
    window.history.replaceState({}, '', '/?mock=files&files-scenario=anomalies');
    const real = vi.fn(() => { throw new Error('REAL API MUST NOT RUN'); });
    const desktop = vi.fn(); window.plannerDesktop = { showFileInFolder: desktop };
    const network = vi.fn(); vi.stubGlobal('fetch', network);
    render(<App api={new Proxy({}, { get: () => real }) as never} />);
    await screen.findByText('包装箱-002-转曲后');
    fireEvent.click(screen.getByRole('button', { name: '产品／批次导航' }));
    fireEvent.change(screen.getByLabelText('存在状态'), { target: { value: 'all' } });
    fireEvent.click(screen.getByRole('button', { name: '筛选 PDF' }));
    fireEvent.click(screen.getByRole('button', { name: '关闭产品导航' }));
    await screen.findByText('说明书-001-源文件');
    expect(document.querySelector('.file-match.pending .files-match-badge')?.textContent).toBe('待确认');
    expect(document.querySelector('.file-match.conflict .files-match-badge')?.textContent).toBe('多图号冲突');
    fireEvent.click(screen.getAllByRole('button', { name: /清理 .* 的索引记录/ })[0]);
    fireEvent.click(screen.getByRole('button', { name: '确认清理索引记录' }));
    await screen.findByText('已清理 1 条缺失 PDF 索引记录');
    expect(screen.queryByText('说明书-001-源文件')).not.toBeInTheDocument();
    fireEvent.click(screen.getByRole('button', { name: '扫描资料库' }));
    fireEvent.click(await screen.findByRole('button', { name: '取消模拟扫描' }));
    await screen.findByRole('alert');
    expect(real).not.toHaveBeenCalled(); expect(network).not.toHaveBeenCalled(); expect(desktop).not.toHaveBeenCalled();
  });
  it('aggregates navigation over every filtered mock row while keeping navigation scope separate', async () => {
    const api = createFilesMockApi('normal');
    const filters = {presence:'all',conversionType:'source'};
    const result = await api.searchPdfFiles({...filters,pageSize:1000});
    const counts = await api.getPdfFileNavigation!(filters);
    expect(counts.total).toBe(result.total);
    expect(counts.unassociatedProducts).toBe(result.items.filter(row => row.productId === null).length);
    const orphan = await api.searchPdfFiles({...filters,unassociatedProduct:'true',pageSize:1000});
    expect(orphan.total).toBe(counts.unassociatedProducts);
    expect(orphan.items.every(row => row.productId === null)).toBe(true);
  });
  it('keeps filters and pagination independent and returns cloned fixture data', async () => {
    const api = createFilesMockApi('normal');
    const first = await api.searchPdfFiles({ presence: 'all', page: 1, pageSize: 50 });
    const second = await api.searchPdfFiles({ presence: 'all', page: 2, pageSize: 50 });
    expect(first.items).toHaveLength(50); expect(second.items).toHaveLength(50);
    expect(first.items[0].id).toBe(-1001); expect(second.items[0].id).toBe(-1051);
    first.items[0].fileName = 'mutated';
    expect((await api.searchPdfFiles({ presence: 'all' })).items[0].fileName).toBe('说明书-001-源文件.pdf');
    const selected = await api.searchPdfFiles({ presence: 'all', materialBatchId: -302, conversionType: 'outlined' });
    expect(selected.total).toBe(38);
    expect(selected.items.every(row => row.materialBatchId === -302 && row.conversionType === 'outlined')).toBe(true);
  });
  it.each(['empty', 'no-results', 'error'] as const)('models %s without a real fallback', async scenario => {
    const api = createFilesMockApi(scenario);
    if (scenario === 'error') await expect(api.searchPdfFiles()).rejects.toThrow(/加载失败/);
    else expect((await api.searchPdfFiles()).total).toBe(0);
  });
  it('preserves memory indices when a simulated scan fails', async () => {
    const api = createFilesMockApi('scan-error');
    await expect(api.scanPdfFiles()).rejects.toThrow(/未更改/);
    expect((await api.searchPdfFiles({ presence: 'all' })).total).toBe(150);
  });
});
